import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {bookingGroup,admissionStatus,organizerStats,guestCsv} from '../frontend/src/features/bookings/bookingTools.js';
const require=createRequire(new URL('../frontend/package.json',import.meta.url));
const {build}=require('esbuild');
const Module=require('node:module');
const output=await build({entryPoints:[fileURLToPath(new URL('../frontend/src/features/bookings/TicketDownload.jsx',import.meta.url))],bundle:true,platform:'node',format:'cjs',write:false});
const compiled=new Module('ticket-download');compiled._compile(output.outputFiles[0].text,'ticket-download.cjs');
const {ticketDocument}=compiled.exports;
const sample={id:1,quantity:2,status:'CONFIRMED',startsAt:'2035-01-01T10:00:00',total:300,customerName:'<script>alert(1)</script>',customerEmail:'guest@example.test',eventTitle:'Music & Friends',venue:'Hall <A>',reference:'LT-EXAMPLE',tickets:[{id:1,seatLabel:'GA-0001',status:'CHECKED_IN',qrPayload:'LT1.one.signature'},{id:2,seatLabel:'GA-0002',status:'BOOKED',qrPayload:'LT1.two.signature'}]};
assert.equal(bookingGroup(sample,0),'Upcoming');
assert.equal(bookingGroup({...sample,startsAt:'2000-01-01'},Date.now()),'Past');
assert.equal(bookingGroup({...sample,status:'CANCELLED'},0),'Cancelled');
assert.equal(admissionStatus(sample),'1/2 checked in');
assert.equal(admissionStatus({...sample,status:'CANCELLED'}),'Cancelled');
assert.deepEqual(organizerStats([{startsAt:'2035-01-01',available:8}],[sample,{...sample,status:'CANCELLED'}]),{bookings:1,sold:2,remaining:8,checkedIn:1,value:300});
const csv=guestCsv([{...sample,customerName:'=HYPERLINK("x")',eventTitle:'Music, "Friends"'}]);
assert.ok(csv.includes('"\'=HYPERLINK(""x"")"'));assert.ok(csv.includes('"Music, ""Friends"""'));assert.ok(csv.includes('1/2 checked in'));
const html=ticketDocument(sample);
assert.equal((html.match(/<svg/g)||[]).length,2);
assert.ok(html.includes('Music &amp; Friends'));assert.ok(html.includes('Hall &lt;A&gt;'));
assert.ok(!html.includes('<script>'));assert.ok(html.includes('LT-EXAMPLE'));assert.ok(html.includes('Print / Save as PDF'));assert.ok(html.includes('Already checked in'));
console.log('PASS: booking groups, check-in statuses, organizer totals, CSV quoting/formula protection, offline ticket fields, unique QR rendering and HTML escaping.');
